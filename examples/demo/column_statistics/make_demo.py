def _caption(stat: columns.ColumnStats) -> str:
    parts = [f"<code>{html.escape(stat.column)}</code>"]
    if len(stat.columns) > 1:
        others = ", ".join(html.escape(c) for c in stat.columns[1:])
        parts.append(f'<span class="meta">with {others}</span>')
    detail = (
        f"{stat.kind}, {stat.filled:,} filled, {stat.empty:,} empty, "
        f"{stat.distinct:,} distinct"
    )
    if stat.summary:
        detail += (
            f"; quartiles {stat.summary['q1']:.4g} / {stat.summary['median']:.4g} / "
            f"{stat.summary['q3']:.4g}"
        )
    parts.append(f'<span class="meta">{detail}</span>')
    return "".join(f"<div>{part}</div>" for part in parts)


def _section(name: str, path: str) -> str:
    table = flat.flatten(datasets.load_dataset(path).reactions)
    stats = columns.column_statistics(table)
    figures = [
        f'<figure class="{stat.section}"><figcaption>{_caption(stat)}</figcaption>'
        f"{stat.to_svg()}</figure>"
        for stat in stats
    ]
    summary = (
        f"{table.reaction_count:,} reactions; {len(table.varying.columns):,} varying "
        f"columns in {len(stats):,} groups; {len(table.constants):,} constant columns."
    )
    return (
        f"<section><h2>{html.escape(name)}</h2><p>{summary}</p>"
        f'<div class="grid">{"".join(figures)}</div></section>'
    )


def main() -> None:
    """Parses arguments and writes the page."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=pathlib.Path)
    parser.add_argument("datasets", nargs="+")
    args = parser.parse_args()
    sections = []
    for spec in args.datasets:
        name, _, path = spec.rpartition("=")
        sections.append(_section(name or pathlib.Path(path).name, path))
    args.output.write_text(
        _HEADER + "\n".join(sections) + "\n</main>\n</body>\n</html>\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
